#!/usr/bin/env bash
# Regenerate a hash-locked install set from its direct-dependency .in file.
# With no arguments, preserve the backend requirements.in -> requirements.txt workflow.
# pip enforces the hashes on every install (Docker, CI, start-local-python.sh), so a
# transitive package can no longer change between builds without a reviewed diff here.
set -euo pipefail
repo_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
command -v uv >/dev/null 2>&1 || { printf 'Missing uv: https://docs.astral.sh/uv/\n' >&2; exit 1; }
if [[ "$#" -ne 0 && "$#" -ne 2 ]]; then
  printf 'Usage: %s [requirements.in requirements.txt]\n' "$0" >&2
  exit 1
fi
cd "$repo_dir"
in_path="${1:-backend/requirements.in}"
out_path="${2:-backend/requirements.txt}"
in_file="$in_path"
out_file="$out_path"
python3 scripts/check-dependency-age.py "$in_file"
setting() { sed -n "s/^# $1: *//p" "$in_file"; }
want_uv="$(setting uv-version)"
have_uv="$(uv --version | cut -d' ' -f2)"
if [[ "$have_uv" != "$want_uv" ]]; then
  printf 'uv %s is required (%s uv-version); found %s.\n' "$want_uv" "$in_path" "$have_uv" >&2
  exit 1
fi
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
# Bound the universal resolve to the Python versions each consumer supports.
python3 - "$in_file" "$work/pyproject.toml" "$(setting uv-exclude-newer)" \
  "$(setting requires-python)" "$(setting environments)" <<'PY'
import json, sys
deps = [line.split('#')[0].strip() for line in open(sys.argv[1])]
deps = [d for d in deps if d]
with open(sys.argv[2], 'w') as out:
    out.write('[project]\nname = "cozy-commons-backend-lock"\nversion = "0"\n')
    out.write('requires-python = ' + json.dumps(sys.argv[4] or '>=3.12') + '\n')
    out.write('dependencies = ' + json.dumps(deps) + '\n')
    # uv ignores upper requires-python bounds; environments is what limits the universal resolve.
    out.write('[tool.uv]\npackage = false\nenvironments = ' + json.dumps([sys.argv[5] or "python_version >= '3.12' and python_version < '3.14'"]) + '\n')
    # A fixed cutoff makes the resolve reproducible, so CI can check the lock against this file.
    out.write('exclude-newer = ' + json.dumps(sys.argv[3]) + '\n')
PY
{
  printf '# Generated by scripts/lock-backend-requirements.sh from %s. Do not edit.\n' "${in_path#"$repo_dir/"}"
  # --no-config and an explicit index: ambient uv.toml or UV_* index settings cannot change the source.
  (cd "$work" && unset UV_INDEX UV_INDEX_URL UV_DEFAULT_INDEX UV_EXTRA_INDEX_URL UV_FIND_LINKS UV_EXCLUDE_NEWER UV_CONFIG_FILE UV_RESOLUTION UV_PRERELEASE \
     && uv lock --quiet --no-config --default-index https://pypi.org/simple \
     && uv export --quiet --no-config --frozen --format requirements-txt \
     --no-header --no-annotate --no-emit-project)
} > "$work/requirements.txt"
mv "$work/requirements.txt" "$out_file"
printf 'Locked %s packages into %s\n' "$(grep -c '^[A-Za-z0-9]' "$out_file")" "$out_path"
