#!/usr/bin/env bash
# Regenerate backend/requirements.txt, the hash-locked install set, from backend/requirements.in.
# pip enforces the hashes on every install (Docker, CI, start-local-python.sh), so a
# transitive package can no longer change between builds without a reviewed diff here.
set -euo pipefail
repo_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
command -v uv >/dev/null 2>&1 || { printf 'Missing uv: https://docs.astral.sh/uv/\n' >&2; exit 1; }
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
# The universal resolve needs an upper Python bound; production runs 3.12 and local dev 3.12-3.13.
python3 - "$repo_dir/backend/requirements.in" "$work/pyproject.toml" <<'PY'
import json, sys
deps = [line.split('#')[0].strip() for line in open(sys.argv[1])]
deps = [d for d in deps if d]
with open(sys.argv[2], 'w') as out:
    out.write('[project]\nname = "cozy-commons-backend-lock"\nversion = "0"\n')
    out.write('requires-python = ">=3.12"\n')
    out.write('dependencies = ' + json.dumps(deps) + '\n')
    # uv ignores upper requires-python bounds; environments is what limits the universal resolve.
    out.write('[tool.uv]\npackage = false\nenvironments = ["python_version >= \'3.12\' and python_version < \'3.14\'"]\n')
PY
{
  printf '# Generated by scripts/lock-backend-requirements.sh from backend/requirements.in. Do not edit.\n'
  (cd "$work" && uv lock --quiet && uv export --quiet --frozen --format requirements-txt \
     --no-header --no-annotate --no-emit-project)
} > "$repo_dir/backend/requirements.txt.new"
mv "$repo_dir/backend/requirements.txt.new" "$repo_dir/backend/requirements.txt"
printf 'Locked %s packages into backend/requirements.txt\n' "$(grep -c '^[A-Za-z0-9]' "$repo_dir/backend/requirements.txt")"
