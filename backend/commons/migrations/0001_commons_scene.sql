-- Shared Cozy Commons scene state. The API is the only writer; the browser
-- never receives direct table or RPC access.

create table public.commons_scenes (
  id text primary key,
  layout_version integer not null default 1 check (layout_version > 0),
  version integer not null default 0 check (version >= 0),
  state jsonb not null check (jsonb_typeof(state) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.commons_scene_commands (
  id bigint generated by default as identity primary key,
  scene_id text not null references public.commons_scenes(id) on delete cascade,
  actor_key text not null check (char_length(actor_key) between 1 and 128),
  client_command_id text not null check (char_length(client_command_id) between 1 and 128),
  expected_version integer not null check (expected_version >= 0),
  accepted_version integer not null check (accepted_version > 0),
  canonical_payload jsonb not null check (jsonb_typeof(canonical_payload) = 'object'),
  resulting_state jsonb not null check (jsonb_typeof(resulting_state) = 'object'),
  created_at timestamptz not null default now(),
  unique (scene_id, actor_key, client_command_id)
);

create index commons_scene_commands_version_idx
  on public.commons_scene_commands (scene_id, accepted_version);

grant usage, select on sequence public.commons_scene_commands_id_seq to service_role;

alter table public.commons_scenes enable row level security;
alter table public.commons_scene_commands enable row level security;

revoke all on table public.commons_scenes from public, anon, authenticated;
revoke all on table public.commons_scene_commands from public, anon, authenticated;

