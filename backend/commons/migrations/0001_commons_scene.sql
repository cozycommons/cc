create or replace function public.commons_apply_command(
  p_scene_id text,
  p_actor_key text,
  p_client_command_id text,
  p_expected_version integer,
  p_canonical_payload jsonb,
  p_resulting_state jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_scene public.commons_scenes%rowtype;
  v_existing public.commons_scene_commands%rowtype;
  v_new_version integer;
begin
  if coalesce(
    nullif(pg_catalog.current_setting('request.jwt.claims', true), '')::jsonb ->> 'role',
    ''
  ) <> 'service_role' then
    return pg_catalog.jsonb_build_object(
      'ok', false,
      'error_code', 'service_role_required'
    );
  end if;

  select * into v_scene
    from public.commons_scenes
   where id = p_scene_id
   for update;

  if not found then
    return pg_catalog.jsonb_build_object(
      'ok', false,
      'error_code', 'scene_not_found'
    );
  end if;

  -- Check idempotency after taking the scene lock so two simultaneous retries
  -- cannot both pass the read-before-write check.
  select * into v_existing
    from public.commons_scene_commands
   where scene_id = p_scene_id
     and actor_key = p_actor_key
     and client_command_id = p_client_command_id;
  if found then
    if v_existing.canonical_payload = p_canonical_payload then
      return pg_catalog.jsonb_build_object(
        'ok', true,
        'replayed', true,
        'scene_id', p_scene_id,
        'accepted_version', v_existing.accepted_version,
        'version', v_scene.version,
        'client_command_id', p_client_command_id,
        'state', v_scene.state
      );
    end if;
    return pg_catalog.jsonb_build_object(
      'ok', false,
      'error_code', 'command_id_conflict'
    );
  end if;

  if v_scene.version <> p_expected_version then
    return pg_catalog.jsonb_build_object(
      'ok', false,
      'error_code', 'stale_version',
      'current_version', v_scene.version
    );
  end if;

  if pg_catalog.jsonb_typeof(p_canonical_payload) <> 'object'
     or pg_catalog.jsonb_typeof(p_resulting_state) <> 'object'
     or not (p_resulting_state ? 'schema_version')
     or not (p_resulting_state ? 'objects')
     or not (p_resulting_state ? 'actors') then
    return pg_catalog.jsonb_build_object(
      'ok', false,
      'error_code', 'invalid_state'
    );
  end if;

  v_new_version := v_scene.version + 1;

  insert into public.commons_scene_commands (
    scene_id, actor_key, client_command_id, expected_version,
    accepted_version, canonical_payload, resulting_state
  ) values (
    p_scene_id, p_actor_key, p_client_command_id, p_expected_version,
    v_new_version, p_canonical_payload, p_resulting_state
  );

  update public.commons_scenes
     set version = v_new_version,
         state = p_resulting_state,
         updated_at = pg_catalog.now()
   where id = p_scene_id;

  return pg_catalog.jsonb_build_object(
    'ok', true,
    'replayed', false,
    'scene_id', p_scene_id,
    'accepted_version', v_new_version,
    'version', v_new_version,
    'client_command_id', p_client_command_id,
    'state', p_resulting_state
  );
end;
$$;

revoke all on function public.commons_apply_command(text, text, text, integer, jsonb, jsonb)
  from public, anon, authenticated;
grant execute on function public.commons_apply_command(text, text, text, integer, jsonb, jsonb)
  to service_role;
